// Bundles the CLI (and the `yaml` dependency) into one file that the composite action runs: action/index.mjs
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
await build({
  entryPoints: ['src/cli.ts'],
  outfile: 'action/index.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: `// node24-ready ${pkg.version} - generated by scripts/bundle.mjs, do not edit\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);` },
  logLevel: 'info',
});
